#!/bin/bash
# Builds what the web app needs that isn't checked in, into Web/build/:
#
#   tables-engine.wasm      the engine from Engine/, compiled for WebAssembly
#   tables-engine.bin       the same, gzipped: what the page loads, as hosts
#                           limit file sizes (Cloudflare: 25 MiB) and it's a third the size.
#                           Not named .gz: Cloudflare's security rules challenge any
#                           request for a .gz file, which a worker's fetch can't pass
#   strings/*.json       a string table for each language
#   version.js           the files the service worker keeps for offline use, and their version
#
# and assembles the site to publish, just the files the page uses, into Web/dist/
# (deployed to Cloudflare from there; see wrangler.jsonc).
#
# Pass --skip-engine to refresh only the strings and version.js, after changing
# the page's own files.
#
# Needs the swift.org toolchain and its Swift SDK for WebAssembly, of the same
# version (see README.md). Override their locations with SWIFT_TOOLCHAIN and SWIFT_SDK.
set -euo pipefail

WEB="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(dirname "$WEB")"
TOOLCHAIN="${SWIFT_TOOLCHAIN:-$HOME/Library/Developer/Toolchains/swift-6.4.2-RELEASE.xctoolchain}"
SWIFT="$TOOLCHAIN/usr/bin/swift"
SDK="${SWIFT_SDK:-swift-6.4.2-RELEASE_wasm}"

cd "$WEB/engine/swift"
mkdir -p "$WEB/build"
if [[ "${1:-}" != "--skip-engine" ]]; then
    echo "Building the engine…"
    "$SWIFT" build --swift-sdk "$SDK" --product TablesWasm -c release -Xswiftc -gnone -Xlinker --strip-all
    BIN="$("$SWIFT" build --swift-sdk "$SDK" --product TablesWasm -c release -Xswiftc -gnone -Xlinker --strip-all --show-bin-path)"
    cp "$BIN/TablesWasm.wasm" "$WEB/build/tables-engine.wasm"
fi
if [[ ! "$WEB/build/tables-engine.bin" -nt "$WEB/build/tables-engine.wasm" ]]; then
    echo "Compressing the engine…"
    gzip -9 -n -c "$WEB/build/tables-engine.wasm" > "$WEB/build/tables-engine.bin"
fi

echo "Converting strings…"
"$SWIFT" run -c release strings-tool "$WEB/build/strings" \
    "app=$WEB/strings/Localizable.xcstrings,$ROOT/Engine/TablesEngine/Localizable.xcstrings,$ROOT/Engine/TablesMacros/Localizable.xcstrings"

echo "Listing files for offline use…"
cd "$WEB"
FILES=$( { echo index.html; echo manifest.webmanifest;
    find app design engine build -type f \( -name "*.js" -o -name "*.css" -o -name "*.json" -o -name "*.bin" -o -name "*.png" -o -name "*.svg" \) \
        -not -path "engine/swift/.build/*" -not -path "engine/swift/Sources/*" -not -name "lint.mjs" -not -name "serve.mjs" -not -name "version.js"; } | sort)
if command -v sha256sum > /dev/null; then SHA256="sha256sum"; else SHA256="shasum -a 256"; fi
VERSION=$(echo "$FILES" | xargs $SHA256 | $SHA256 | cut -c1-16)
APP_VERSION=$(sed -nE 's/^[[:space:]]*"version"[[:space:]]*:[[:space:]]*"([^"]+)".*/\1/p' "$WEB/package.json" | head -1)
{
    echo "// Generated by build.sh: the app's version, and the files sw.js keeps for offline use."
    echo "self.TABLES_APP_VERSION = \"$APP_VERSION\";"
    echo "self.TABLES_VERSION = \"$VERSION\";"
    echo "self.TABLES_FILES = ["
    echo '  "./",'
    echo "$FILES" | sed 's|.*|  "./&",|'
    echo "];"
} > "$WEB/build/version.js"

echo "Assembling the site…"
rm -rf "$WEB/dist"
mkdir -p "$WEB/dist"
{ echo "$FILES"; echo sw.js; echo build/version.js; } | while read -r file; do
    mkdir -p "$WEB/dist/$(dirname "$file")"
    cp "$file" "$WEB/dist/$file"
done
cp "$WEB/deploy/_headers" "$WEB/deploy/robots.txt" "$WEB/deploy/sitemap.xml" "$WEB/dist/"
# For links shared on social sites; not kept offline.
mkdir -p "$WEB/dist/social"
cp "$WEB/social/og-image.png" "$WEB/dist/social/"
# Cloudflare serves files up to 25 MiB.
TOO_BIG=$(find "$WEB/dist" -type f -size +26214400c)
if [[ -n "$TOO_BIG" ]]; then
    echo "Too large to publish (over 25 MiB): $TOO_BIG" >&2
    exit 1
fi

echo "Built Tables $APP_VERSION (build $VERSION, $(du -h "$WEB/build/tables-engine.wasm" | cut -f1) engine, $(du -h "$WEB/build/tables-engine.bin" | cut -f1) compressed) into $WEB/build and $WEB/dist"
